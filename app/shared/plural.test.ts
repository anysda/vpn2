import { describe, expect, it } from 'vitest'
import { pluralRu } from './plural'

const forms: [string, string, string] = ['устройство', 'устройства', 'устройств']

describe('pluralRu', () => {
  it.each([
    [1, 'устройство'],
    [2, 'устройства'],
    [5, 'устройств'],
    [21, 'устройство'],
    [111, 'устройств'],
    [0, 'устройств'],
    [11, 'устройств'],
    [12, 'устройств'],
    [14, 'устройств'],
    [22, 'устройства'],
    [25, 'устройств'],
    [101, 'устройство'],
    [112, 'устройств'],
    [-1, 'устройство'],
    [-5, 'устройств']
  ])('%i -> %s', (n, expected) => {
    expect(pluralRu(n, forms)).toBe(expected)
  })
})
