// Ступени сетки «Активность»: 0 — пустой день, 1–4 — оттенки от светлого к тёмному.
// Пороги берутся из самих ненулевых дней показанного периода (квартили), а не
// от доли максимума: тогда сетка одинаково различает дни и у панели на трёх
// клиентов, и на трёхстах, и один пиковый день не гасит все остальные.

/** Возвращает функцию «значение дня → ступень 0..4» для набора значений периода. */
export function activityScale(values: number[]): (v: number) => number {
  const s = values.filter(v => v > 0).sort((a, b) => a - b)
  const u = [...new Set(s)]
  if (u.length <= 4) {
    // различимых значений не больше ступеней: каждому своя, большее — темнее,
    // наибольшее всегда на самой тёмной
    const step = new Map(u.map((v, i) => [v, u.length === 1 ? 4 : 1 + Math.round(i * 3 / (u.length - 1))]))
    return v => v > 0 ? step.get(v) ?? 4 : 0
  }
  // пороги — значения на границах четвертей ненулевых дней
  const th = [1, 2, 3].map(k => s[Math.floor(k * s.length / 4)]!)
  return v => v > 0 ? 1 + th.filter(t => v >= t).length : 0
}
