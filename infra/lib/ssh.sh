#!/usr/bin/env bash
# Shared helpers for deploy.sh and individual stage scripts.
# Source this from any script that needs to SSH into a target host.

set -euo pipefail

DEPLOY_ROOT="${DEPLOY_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

# Color helpers (terminal-safe)
if [[ -t 1 ]]; then
  C_R='\033[31m' C_G='\033[32m' C_Y='\033[33m' C_B='\033[34m' C_END='\033[0m'
else
  C_R= C_G= C_Y= C_B= C_END=
fi
log()  { printf '%b[%s]%b %s\n' "$C_B" "${HOST_TAG:-?}" "$C_END" "$*" >&2; }
ok()   { printf '%b[%s]%b %s\n' "$C_G" "${HOST_TAG:-?}" "$C_END" "$*" >&2; }
warn() { printf '%b[%s]%b %s\n' "$C_Y" "${HOST_TAG:-?}" "$C_END" "$*" >&2; }
die()  { printf '%b[%s] FATAL:%b %s\n' "$C_R" "${HOST_TAG:-?}" "$C_END" "$*" >&2; exit 1; }

# Load env for a host. Usage: load_env ru
load_env() {
  local host="$1"
  set -a
  # shellcheck disable=SC1091
  source "$DEPLOY_ROOT/envs/all.env" || { set +a; return 1; }
  if [[ -f "$DEPLOY_ROOT/envs/$host.env" ]]; then
    # shellcheck disable=SC1091
    source "$DEPLOY_ROOT/envs/$host.env" || { set +a; return 1; }
  else
    die "no env for host '$host'"
  fi
  set +a
}

# Expand HOST_GROUP to list of host tags.
# Exit tags are read dynamically from envs/exits.env (generated by config2env.py).
expand_hosts() {
  local group="$1"
  local exits="" configured_exits="" tag
  if [[ -f "$DEPLOY_ROOT/envs/exits.env" ]]; then
    # shellcheck disable=SC1091
    source "$DEPLOY_ROOT/envs/exits.env"
    exits="${EXIT_TAGS:-}"
  fi
  configured_exits="$exits"

  # Полный EXIT_TAGS остаётся в env хаба: 20-ru-router, monitoring и панель
  # должны хранить конфигурацию даже временно недоступного экзита. Этот список
  # отсекает такие ноды только от fan-out стадий текущего полного деплоя.
  local active=()
  for tag in $exits; do
    grep -qw -- "$tag" <<<"${SKIPPED_EXIT_TAGS:-}" || active+=("$tag")
  done
  exits="${active[*]}"

  case "$group" in
    ru)      echo ru ;;
    foreign) [[ -n "$configured_exits" ]] || die "EXIT_TAGS пустой — перезапусти ./deploy.sh"
             echo "$exits" ;;
    all)     [[ -n "$configured_exits" ]] || die "EXIT_TAGS пустой — перезапусти ./deploy.sh"
             echo "ru $exits" ;;
    *)       # Конкретный тег — проверяем что он есть в списке экзитов
             if grep -qw -- "$group" <<<"$exits"; then
               echo "$group"
             else
               die "unknown host group: $group (доступные: ru foreign all или тег из config.yaml)"
             fi ;;
  esac
}

# Авторизация: сначала pubkey (если ~/.ssh/id_* подходит), потом пароль через
# sshpass. Это позволяет 00-bootstrap залить публичный ключ оркестратора на
# ноду и отключить парольный вход — последующие стадии пойдут по ключу.
# SSHPASS экспортируется per-call чтобы пароль не светился в `ps aux`.
#
# Host-key policy: первое подключение к ноде закрепляет её host-key в
# $DEPLOY_ROOT/.known_hosts (TOFU). При повторном деплое подмена ключа =
# отказ соединения.
_known_hosts="${DEPLOY_ROOT}/.known_hosts"
[[ -f "$_known_hosts" ]] || { touch "$_known_hosts"; chmod 600 "$_known_hosts"; }
_ssh_opts=(
  -o StrictHostKeyChecking=accept-new
  -o UserKnownHostsFile="$_known_hosts"
  -o LogLevel=ERROR
  -o PreferredAuthentications=publickey,password
  -o PubkeyAuthentication=yes
  -o ConnectTimeout=10
  -o ConnectionAttempts=3
  -o ServerAliveInterval=15
)

# Одно ssh-соединение на ноду вместо нового рукопожатия на каждый вызов: стадия
# на ноде - это 5-7 вызовов ssh/scp (push env, push скрипта, ожидание apt,
# запуск), по полсекунды на каждый. Master живёт 60 с после последнего вызова.
# Сбой master'а ssh_exec/push видят как rc=255 и ретраят новым соединением.
_ssh_mux_dir="/tmp/anysda-ssh-$(id -u)"
if { [[ -d "$_ssh_mux_dir" ]] || mkdir -m 700 "$_ssh_mux_dir" 2>/dev/null; } && [[ -O "$_ssh_mux_dir" ]]; then
  _ssh_opts+=(
    -o ControlMaster=auto
    -o ControlPath="$_ssh_mux_dir/%C"
    -o ControlPersist=60
  )
fi

# Run a command on the current $SSH_HOST. Args are passed to ssh.
# Ретраит транзиентные сбои соединения: у VPS-экзитов SSH иногда флапает
# (таймаут / "connection closed" / banner exchange), и один такой сбой
# посреди стадии не должен ронять весь деплой.
ssh_exec() {
  : "${SSH_PASS:?SSH_PASS не задан (перезапусти ./setup.sh)}"
  local attempt rc=0
  for attempt in 1 2 3 4 5; do
    rc=0
    SSHPASS="$SSH_PASS" sshpass -e ssh "${_ssh_opts[@]}" \
        "${SSH_USER}@${SSH_HOST}" "$@" || rc=$?
    # rc=255 — сбой самого ssh (соединение). Любой другой код — это exit
    # удалённой команды (напр. `test -f` для idempotency-штампа), отдаём как есть.
    [[ $rc -ne 255 ]] && return $rc
    [[ $attempt -eq 1 ]] && _ssh_refusal_final && return $rc
    [[ $attempt -lt 5 ]] && { warn "ssh ${SSH_HOST}: сбой соединения, повтор ${attempt}/4"; sleep $((attempt * 3)); }
  done
  return $rc
}

# Причина отказа ssh по коду выхода и stderr: hostkey | auth | net.
# Смена host-key - всегда rc=255 с этим текстом у OpenSSH, неверный пароль
# sshpass отдаёт кодом 5. Всё прочее (refused, таймаут, обрыв) - сеть.
ssh_fail_kind() {
  local rc="$1" err="$2"
  case $rc in 5) echo auth; return ;; 124|137) echo net; return ;; esac
  case $err in
    *'REMOTE HOST IDENTIFICATION HAS CHANGED'*|*'Host key verification failed'*) echo hostkey ;;
    *'Permission denied'*|*'Too many authentication failures'*) echo auth ;;
    *) echo net ;;
  esac
}

# Команда, которой человек сам убирает старый host-key ноды. Сами ключ не
# принимаем: сменившийся ключ - это и переустановка ОС, и подмена ноды.
ssh_hostkey_fix() {
  printf 'ssh-keygen -R %s -f %s' "$SSH_HOST" "$_known_hosts"
}

# После rc=255 у стадии: сменившийся host-key и отказ во входе повтором не
# лечатся, а четыре «сбой соединения, повтор» выглядят как флап сети. Одна
# проба решает. Отказ во входе повторять нельзя ещё и потому, что fail2ban
# экзита считает каждый неудачный пароль и банит адрес entry.
_ssh_refusal_final() {
  local reason prc=0
  reason=$(ssh_probe) || prc=$?
  case $prc in
    2) warn "ssh ${SSH_HOST}: ${reason}; новый ключ сам не принимается (защита от подмены ноды)"
       warn "если ОС на ноде переустанавливали, убери старый ключ и повтори: $(ssh_hostkey_fix)" ;;
    3) _ssh_auth_refused "$reason" ;;
    *) return 1 ;;
  esac
}

_ssh_auth_refused() {
  warn "ssh ${SSH_HOST}: $1; повтор не нужен: проверь пароль ноды в config.yaml и ключ оркестратора на ноде"
}

# Короткая проверка «нода пускает по ssh»: одна попытка с общим потолком
# времени, причина отказа - в stdout. ConnectTimeout ограничивает только
# TCP-коннект и ожидание баннера: если фильтр по пути пропускает их, а пакеты
# обмена ключами режет, ssh висит, а ssh_exec повторяет это 5 раз. Потолок 30 с:
# у живой, но медленной ноды коннект и баннер укладываются в ConnectTimeout=10,
# KEX и вход по паролю - в единицы секунд, остаётся запас на DNS у sshd.
# Свежее соединение без мультиплексора: зависший master не должен отвечать
# за ноду, а опции до _ssh_opts, потому что у ssh побеждает первое значение.
# Код возврата - класс отказа: 1 сеть или прочее, 2 сменился host-key,
# 3 нода отказала во входе.
ssh_probe() {
  : "${SSH_PASS:?SSH_PASS не задан (перезапусти ./setup.sh)}"
  local limit="${SSH_PROBE_TIMEOUT:-30}" err last rc=0
  err=$(SSHPASS="$SSH_PASS" timeout -k 5 "$limit" sshpass -e ssh \
      -o ConnectionAttempts=1 -o ControlMaster=no -o ControlPath=none \
      "${_ssh_opts[@]}" "${SSH_USER}@${SSH_HOST}" 'echo ok' 2>&1 >/dev/null) || rc=$?
  [[ $rc -eq 0 ]] && return 0
  last=$(printf '%s\n' "$err" | tr -d '\r' | sed '/^[[:space:]]*$/d' | tail -1)
  case $(ssh_fail_kind "$rc" "$err") in
    hostkey) echo "сменился host-key ноды (например, после переустановки ОС)${last:+: $last}"; return 2 ;;
    auth)    [[ $rc -eq 5 ]] && last="неверный пароль"
             echo "нода отказала во входе: $last"; return 3 ;;
  esac
  case $rc in
    124|137) echo "нет ответа за ${limit} с${last:+ ($last)}: соединение или обмен ключами ssh висит, пакеты режутся по пути" ;;
    6)       echo "host-key ноды не принят${last:+: $last}" ;;
    *)       echo "${last:-ssh завершился с кодом $rc}" ;;
  esac
  return 1
}

# Одна команда по новому соединению, без мультиплексора и повторов: так
# проверяется, что нода пускает новые входы, а не живёт старое соединение.
ssh_fresh() {
  : "${SSH_PASS:?SSH_PASS не задан (перезапусти ./setup.sh)}"
  SSHPASS="$SSH_PASS" timeout -k 5 "${SSH_PROBE_TIMEOUT:-30}" sshpass -e ssh \
      -o ConnectionAttempts=1 -o ControlMaster=no -o ControlPath=none \
      "${_ssh_opts[@]}" "${SSH_USER}@${SSH_HOST}" "$@"
}

# Copy a local file/dir to the host's /tmp/anysda.
# Один вызов ssh на файл: scp ходит по SFTP и до экзита стоит ~0,55 с против
# ~0,12 с у exec через тот же мультиплексор, а с mkdir и mv push был тремя
# вызовами. Файл пишем под временным именем и переименовываем: оборванная
# передача не оставляет на узле недописанный файл. Режим - как у источника (env с
# секретами - 600). Каталог заменяется целиком, а не вкладывается внутрь
# старого.
push() {
  local src="$1" dst="${2:-}"
  local target="/tmp/anysda/$(basename "$src")"
  [[ -n "$dst" ]] && target="/tmp/anysda/$dst"
  : "${SSH_PASS:?SSH_PASS не задан (перезапусти ./setup.sh)}"
  local tmp="${target}.$BASHPID.$RANDOM" cmd
  if [[ -d "$src" ]]; then
    cmd="umask 077 && mkdir -p '$tmp' && tar -xmf - --no-same-owner -C '$tmp' && chmod $(stat -c %a "$src") '$tmp' && rm -rf '$target' && mv '$tmp' '$target'"
  else
    cmd="mkdir -p '$(dirname "$target")' && umask 077 && cat > '$tmp' && chmod $(stat -c %a "$src") '$tmp' && mv -f '$tmp' '$target'"
  fi
  local attempt rc=0
  for attempt in 1 2 3 4 5; do
    rc=0
    if [[ -d "$src" ]]; then
      tar -C "$src" -cf - . | SSHPASS="$SSH_PASS" sshpass -e ssh "${_ssh_opts[@]}" \
          "${SSH_USER}@${SSH_HOST}" "$cmd" || rc=$?
    else
      SSHPASS="$SSH_PASS" sshpass -e ssh "${_ssh_opts[@]}" \
          "${SSH_USER}@${SSH_HOST}" "$cmd" < "$src" || rc=$?
    fi
    [[ $rc -eq 0 ]] && return 0
    # Код 5 у sshpass - неверный пароль (удалённые mkdir/cat/mv/tar им не
    # выходят): без пробы, она стоила бы ноде ещё одну строку для fail2ban.
    [[ $rc -eq 5 ]] && { _ssh_auth_refused 'нода отказала во входе: неверный пароль'; return $rc; }
    [[ $attempt -eq 1 && $rc -eq 255 ]] && _ssh_refusal_final && return $rc
    ssh_exec "rm -rf '$tmp'" >/dev/null 2>&1 || true
    [[ $attempt -lt 5 ]] && { warn "push → ${SSH_HOST}: сбой, повтор ${attempt}/4"; sleep $((attempt * 3)); }
  done
  return $rc
}
