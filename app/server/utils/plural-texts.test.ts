import { describe, expect, it } from 'vitest'
import { deviceLimitBelowCountText } from './client-ops'
import { inDaysRu } from '../../shared/plural'

describe('строки со склонением', () => {
  it.each([
    [1, 'У клиента уже 1 устройство — лимит не может быть меньше'],
    [2, 'У клиента уже 2 устройства — лимит не может быть меньше'],
    [5, 'У клиента уже 5 устройств — лимит не может быть меньше'],
    [11, 'У клиента уже 11 устройств — лимит не может быть меньше'],
    [21, 'У клиента уже 21 устройство — лимит не может быть меньше'],
    [0, 'У клиента уже 0 устройств — лимит не может быть меньше']
  ])('device_limit_below_count %i', (n, text) => {
    expect(deviceLimitBelowCountText(n)).toBe(text)
  })

  it.each([
    [1, 'через 1 день'],
    [2, 'через 2 дня'],
    [3, 'через 3 дня'],
    [5, 'через 5 дней'],
    [11, 'через 11 дней'],
    [21, 'через 21 день']
  ])('напоминание о сроке %i', (n, text) => {
    expect(inDaysRu(n)).toBe(text)
  })
})
